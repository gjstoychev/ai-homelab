#!/usr/bin/env python3
"""Build results/summary.md: before vs after the board swap, side by side.

Usage: scripts/make-summary.py
Reads, for each phase (before, after) that exists:
  <phase>/04-idle-power.txt, <phase>/11-link-samples.csv,
  results/nvbandwidth-<phase>.csv, results/tps-<phase>.csv
and includes results/summary-findings.md (hand-written) verbatim.
Run scripts/nvbw-to-csv.py and scripts/make-tps-table.py for a phase first.
Missing "after" data shows as "-", so the file is complete before the swap
and fills itself once the after-swap runs exist.
"""
import csv
import pathlib
from collections import Counter

root = pathlib.Path(__file__).resolve().parent.parent
PHASES = ("before", "after")
NAMES = {
    "gemma3-4b": "TranslateGemma 4B", "llama3-8b": "Llama 3 8B (Q4_0)",
    "llama3.1-8b": "Llama 3.1 8B", "qwen3-8b": "Qwen3 8B",
    "qwen2.5-14b": "Qwen2.5 14B", "qwen3-14b": "Qwen3 14B",
    "qwen3.8-27b": "Qwen3.8 27B", "qwen3-30b-a3b": "Qwen3 30B-A3B (MoE)",
    "qwen3-32b": "Qwen3 32B",
}
SCEN = {"gpu0": "1 card, GPU0", "gpu1": "1 card, GPU1",
        "layer": "2 cards, layer", "tensor": "2 cards, tensor",
        "layer-mtp": "2 cards, layer + MTP", "tensor-mtp": "2 cards, tensor + MTP"}
ENGINES = ("llama-bench", "llama-server", "Ollama")
models = [l.split("\t")[0] for l in (root / "scripts/models.tsv").read_text().splitlines()
          if l and not l.startswith("#")]


def read_csv(path):
    return list(csv.DictReader(open(path))) if path.exists() else []


def fmt(x, d=1):
    return "-" if x is None else f"{x:.{d}f}"


def delta(a, b):
    return "-" if a is None or b is None else f"{(b / a - 1) * 100:+.1f} %"


def idle_power(phase):
    f = root / phase / "04-idle-power.txt"
    if not f.exists():
        return {}
    w = {}
    for line in f.read_text().splitlines():
        p = [x.strip() for x in line.split(",")]
        if len(p) > 3 and p[0][:4].isdigit() and p[3].endswith("W"):
            w.setdefault(p[1], []).append(float(p[3].split()[0]))
    return {g: sum(v) / len(v) for g, v in w.items()}


def link_under_load(phase):
    rows = read_csv(root / phase / "11-link-samples.csv")
    c = {}
    for r in rows:
        r = {k.strip(): v.strip() for k, v in r.items()}
        if r["pcie.link.gen.current"] != "1":
            c.setdefault(r["index"], Counter())[
                f"Gen{r['pcie.link.gen.current']} x{r['pcie.link.width.current']}"] += 1
    return {g: v.most_common(1)[0][0] for g, v in c.items()}


md = ["# Board swap: before vs after", "",
      "Generated by `scripts/make-summary.py` from the raw results; the findings",
      "section is `results/summary-findings.md`. Before: NZXT N7 Z790, GPU1 on a",
      "chipset Gen4 x4 link. After: ASUS ROG Maximus Z690 Formula, both GPUs on CPU",
      "lanes (x8/x8). `-` = not measured (yet). Change = after vs before.", ""]

findings = root / "results/summary-findings.md"
if findings.exists():
    md += [findings.read_text().rstrip(), ""]

# Models and settings (from results/tps-<phase>.csv)
settings = {}
for ph in PHASES:
    for r in read_csv(root / f"results/tps-{ph}.csv"):
        d = settings.setdefault(r["model"], {"quant": r.get("quant", ""), "kv": set()})
        if r.get("kv_cache"):
            d["kv"].add(r["kv_cache"].replace(" (default)", ""))
if settings:
    md += ["## Models and settings", "",
           "Same GGUF files before and after. KV cache type as recorded per run",
           "(llama-bench, Ollama logs) or set by default (llama-server). Context 4096",
           "tokens for llama-server and Ollama, flash attention on everywhere.", "",
           "| Model | Weights | KV cache (K/V) |", "|---|---|---|"]
    for m in models:
        if m in settings:
            md.append(f"| {NAMES.get(m, m)} | {settings[m]['quant']} | "
                      f"{', '.join(sorted(settings[m]['kv']))} |")
    md.append("")

# Links and idle power
links = {p: link_under_load(p) for p in PHASES}
idle = {p: idle_power(p) for p in PHASES}
md += ["## PCIe link and idle power", "",
       "| | GPU0 before | GPU1 before | GPU0 after | GPU1 after |", "|---|---|---|---|---|",
       "| Link under load | " + " | ".join(links[p].get(g, "-") for p in PHASES for g in "01")
       + " |",
       "| Idle power (W) | " + " | ".join(fmt(idle[p].get(g), 2) for p in PHASES for g in "01")
       + " |", ""]

# Bus bandwidth
TESTS = [
    ("host_to_device_memcpy_ce", "host -> GPU, one GPU at a time (GB/s)"),
    ("device_to_host_memcpy_ce", "GPU -> host, one GPU at a time (GB/s)"),
    ("host_to_all_memcpy_ce", "host -> GPU, both GPUs at once (GB/s)"),
    ("all_to_host_memcpy_ce", "GPU -> host, both GPUs at once (GB/s)"),
    ("host_to_device_bidirectional_memcpy_ce", "bidirectional, host -> GPU part (GB/s)"),
    ("device_to_host_bidirectional_memcpy_ce", "bidirectional, GPU -> host part (GB/s)"),
    ("host_device_latency_sm", "host <-> GPU latency (ns)"),
    ("device_local_copy", "VRAM copy, local (GB/s)"),
]
nv = {p: {r["testcase"]: r for r in read_csv(root / f"results/nvbandwidth-{p}.csv")}
      for p in PHASES}


def nvv(p, t, g):
    r = nv[p].get(t)
    return float(r[f"gpu{g}"]) if r else None


md += ["## Bus bandwidth (nvbandwidth, copy engine)", "",
       "| Test | GPU0 before | GPU1 before | GPU0 after | GPU1 after | GPU1 change |",
       "|---|---:|---:|---:|---:|---:|"]
for t, label in TESTS:
    md.append(f"| {label} | " + " | ".join(fmt(nvv(p, t, g), 2) for p in PHASES for g in "01")
              + f" | {delta(nvv('before', t, '1'), nvv('after', t, '1'))} |")
md.append("")

# Tokens per second
tps = {p: {(r["engine"], r["model"], r["scenario"], r["test"]): r
           for r in read_csv(root / f"results/tps-{p}.csv")} for p in PHASES}


def tv(p, e, m, s, t, field="tps"):
    r = tps[p].get((e, m, s, t))
    return float(r[field]) if r and r[field] != "" else None


md += ["## Tokens per second", "",
       "tg = generation (128 tokens), pp = prompt processing. llama-bench:",
       "synthetic pp512/tg128. llama-server and Ollama: same client, ~540-token",
       "text prompt, same server options (1:1 comparable). Mean of 5.", ""]
for e in ENGINES:
    keys = [(m, s) for m in models for s in SCEN
            if any(tv(p, e, m, s, "tg") is not None for p in PHASES)]
    if not keys:
        continue
    md += [f"### {e}", "",
           "| Model | Scenario | tg before | tg after | change | pp before | pp after | change |",
           "|---|---|---:|---:|---:|---:|---:|---:|"]
    for m, s in keys:
        cells = []
        for t in ("tg", "pp"):
            a, b = tv("before", e, m, s, t), tv("after", e, m, s, t)
            cells += [fmt(a), fmt(b), delta(a, b)]
        md.append(f"| {NAMES.get(m, m)} | {SCEN[s]} | " + " | ".join(cells) + " |")
    md.append("")

# Load times
md += ["## Load time (s)", "",
       "llama-server: `docker run` until ready. Ollama: its load_duration. The",
       "first configuration of each model may include a disk read.", "",
       "| Model | Scenario | llama-server before | after | Ollama before | after |",
       "|---|---|---:|---:|---:|---:|"]
for m in models:
    for s in SCEN:
        v = [tv(p, e, m, s, "tg", "load_s") for e in ("llama-server", "Ollama") for p in PHASES]
        if any(x is not None for x in v):
            md.append(f"| {NAMES.get(m, m)} | {SCEN[s]} | " + " | ".join(fmt(x) for x in v) + " |")
md.append("")

(root / "results/summary.md").write_text("\n".join(md))
print(f"wrote results/summary.md ({len(md)} lines)")
