#!/usr/bin/env python3
"""Summarise every run in runs/<model>/ into results/summary.md and .csv.

One row per model and step: the step's own server options (from <step>.cmd,
without the options every run shares), load time, prompt processing and
generation tokens per second (mean and standard deviation of the measured
requests; the warm-up is left out), peak VRAM per GPU, peak server RSS and
page cache, and the mean GPU (both cards) and CPU package power while the
requests ran (the samples after the load time).
"""
import csv
import json
import statistics
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = "--host 127.0.0.1 --port 8080 -np 1 --cache-ram 0 -t 8 -c 8192 -lv 4"


def secs(hms):
    h, m, s = hms.split(":")
    return int(h) * 3600 + int(m) * 60 + float(s)


def ms(values):
    if not values:
        return None, None
    return statistics.mean(values), (statistics.stdev(values) if len(values) > 1 else 0.0)


def step_options(cmd_file):
    for line in cmd_file.read_text().splitlines():
        if line.startswith("command: "):
            return line.split(BASE, 1)[1].strip() if BASE in line else line
    return ""


rows = []
for model_dir in sorted((ROOT / "runs").iterdir()):
    results = model_dir / "results.jsonl"
    if not model_dir.is_dir() or not results.exists():
        continue
    reqs = [json.loads(line) for line in results.read_text().splitlines()]
    for cmd in sorted(model_dir.glob("*.cmd")):
        step = cmd.stem
        mine = [r for r in reqs if r["step"] == step]
        if not mine:
            continue
        load_s = next(r["load_s"] for r in mine if r["kind"] == "warmup")
        meas = [r for r in mine if r["kind"] == "measured"]
        pp, pp_sd = ms([r["pp_tps"] for r in meas])
        tg, tg_sd = ms([r["tg_tps"] for r in meas])

        vram, gpu_w, start = {}, [], None
        with open(model_dir / f"{step}.gpu.csv") as f:
            for rec in csv.reader(f, skipinitialspace=True):
                if rec[0] == "timestamp":
                    continue
                t = datetime.strptime(rec[0], "%Y/%m/%d %H:%M:%S.%f")
                t = t.hour * 3600 + t.minute * 60 + t.second + t.microsecond / 1e6
                start = t if start is None else start
                vram[rec[1]] = max(vram.get(rec[1], 0), int(rec[5].split()[0]))
                if t - start > load_s:
                    gpu_w.append((t, float(rec[3].split()[0])))
        # Both cards are sampled together; sum per timestamp, then average.
        by_t = {}
        for t, w in gpu_w:
            by_t[round(t, 1)] = by_t.get(round(t, 1), 0) + w
        gpu_power = statistics.mean(by_t.values()) if by_t else None

        def after_load(path, col):
            vals, first = [], None
            with open(path) as f:
                for rec in csv.reader(line for line in f if not line.startswith("#")):
                    if not rec or rec[0] == "utc_time" or rec[col] == "":
                        continue
                    t = secs(rec[0])
                    first = t if first is None else first
                    vals.append((t - first, float(rec[col])))
            return [v for dt, v in vals if dt > load_s], [v for _, v in vals]

        cpu_w, _ = after_load(model_dir / f"{step}.cpu.csv", 1)
        # NVMe reads while the requests ran (column added after DeepSeek's step 4).
        with open(model_dir / f"{step}.ram.csv") as f:
            has_disk = "nvme_read_mib" in f.readline()
        nvme, _ = after_load(model_dir / f"{step}.ram.csv", 4) if has_disk else ([], [])
        _, rss = after_load(model_dir / f"{step}.ram.csv", 3)
        _, cache = after_load(model_dir / f"{step}.ram.csv", 2)
        rows.append({
            "model": model_dir.name, "step": step, "options": step_options(cmd),
            "load_s": load_s, "requests": len(meas),
            "pp_tps": pp, "pp_sd": pp_sd, "tg_tps": tg, "tg_sd": tg_sd,
            "vram0_mib": vram.get("0"), "vram1_mib": vram.get("1"),
            "rss_mib": max(rss) if rss else None, "cache_mib": max(cache) if cache else None,
            "gpu_w": gpu_power, "cpu_w": statistics.mean(cpu_w) if cpu_w else None,
            "nvme_gb": (nvme[-1] - nvme[0]) / 1024 if len(nvme) > 1 else None,
        })

out = ROOT / "results"
out.mkdir(exist_ok=True)
with open(out / "summary.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]) if rows else ["model"])
    w.writeheader()
    w.writerows(rows)


def num(v, fmt):
    return "–" if v is None else format(v, fmt)


lines = [
    "# Summary",
    "",
    "Generated by `scripts/summary.py` from `runs/`. t/s: mean ± standard deviation of the measured requests",
    "(prompt about 4260 tokens, 256 generated). Power: mean while the requests ran (both GPUs together; CPU package).",
    "NVMe read: GiB read from the models' disk while the requests ran (recorded from DeepSeek's step 5 on).",
    f"Options every run shares: `{BASE}`.",
    "",
    "| Model | Step | Step options | Load s | Prompt t/s | Generation t/s | VRAM GPU0 / GPU1 MiB | RSS / page cache MiB | GPU W | CPU W | NVMe read GiB |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
]
for r in rows:
    lines.append(
        f"| {r['model']} | {r['step']} | `{r['options'] or '(none)'}` | {num(r['load_s'], '.1f')} "
        f"| {num(r['pp_tps'], '.1f')} ± {num(r['pp_sd'], '.1f')} | {num(r['tg_tps'], '.1f')} ± {num(r['tg_sd'], '.1f')} "
        f"| {r['vram0_mib']} / {r['vram1_mib']} | {r['rss_mib']:.0f} / {r['cache_mib']:.0f} "
        f"| {num(r['gpu_w'], '.0f')} | {num(r['cpu_w'], '.0f')} | {num(r['nvme_gb'], '.1f')} |"
    )
(out / "summary.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
